"""Generate model names and capability tables from the unified runner registry.

Rendering uses only the standard library. Collection imports xDiT in an installed
environment, without constructing pipelines or downloading checkpoints.
"""

import argparse
import copy
import json
import re
from collections import defaultdict
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Callable, Mapping, Sequence

from scripts.docs.generate_cli_reference import _code, _prose


DEFAULT_OUTPUT = Path(__file__).resolve().parents[2] / "docs" / "runner" / "models.md"
IO_METADATA = Path(__file__).with_name("model_reference_io.json")
SOURCE_ROOT = "https://github.com/xdit-project/xDiT/blob/main/"


@dataclass(frozen=True)
class ModelEntry:
    name: str
    aliases: tuple[str, ...]
    source: str
    output: str
    diffusers: str | None
    capabilities: Mapping[str, bool]
    cache_methods: tuple[str, ...]
    inputs: str = "Not declared"


def resolve_model_settings(model: type, config: object) -> object:
    """Run the pre-load settings hook on private copies, without model init."""
    adapter = object.__new__(model)
    adapter.settings = copy.deepcopy(model.settings)
    adapter.default_input_values = copy.deepcopy(getattr(model, "default_input_values", None))
    if hasattr(adapter, "_customize_settings"):
        adapter._customize_settings(config)
    return adapter.settings


def collect_models(
    registry: Mapping[str, type],
    config_factory: Callable[[str], object] | None = None,
    *,
    model_io: Mapping[str, Mapping[str, str]] | None = None,
) -> list[ModelEntry]:
    """Collect declarations and alias-specific presets without loading weights."""
    grouped = defaultdict(list)
    for alias, model in registry.items():
        grouped[model].append(alias)
    if model_io is not None:
        adapter_names = {model.__name__ for model in grouped}
        missing = adapter_names - model_io.keys()
        stale = model_io.keys() - adapter_names
        if missing or stale:
            raise ValueError(f"Review model I/O metadata: missing={sorted(missing)}, stale={sorted(stale)}")
    entries = []
    for model, aliases in grouped.items():
        names = sorted(aliases, key=lambda name: ("/" in name, len(name), name.casefold(), name))
        settings = [
            resolve_model_settings(model, config_factory(alias)) if config_factory else model.settings
            for alias in names
        ]
        methods = {method for setting in settings for method in (setting.step_cache_config or {})}
        io = model_io[model.__name__] if model_io is not None else {}
        entries.append(
            ModelEntry(
                name=names[0],
                aliases=tuple(names),
                source=model.__module__.replace(".", "/") + ".py",
                output=io.get(
                    "output", ", ".join(sorted({setting.model_output_type or "model-specific" for setting in settings}))
                ),
                diffusers=model.min_diffusers_version,
                capabilities=asdict(model.capabilities),
                cache_methods=tuple(sorted(methods)),
                inputs=io["input"] if model_io is not None else "Not declared",
            )
        )
    return sorted(entries, key=lambda entry: (entry.name.casefold(), entry.name))


def _anchor(entry: ModelEntry) -> str:
    return "model-" + re.sub(r"[^a-z0-9]+", "-", entry.name.casefold()).strip("-")


def _flag(entry: ModelEntry, name: str) -> str:
    return "✓" if entry.capabilities.get(name, False) else "—"


def _model_link(entry: ModelEntry, index: int) -> str:
    return f"[{_prose(entry.name)}](#{_anchor(entry)})"


def render_models(entries: Sequence[ModelEntry]) -> str:
    """Render compact tables without importing model execution dependencies."""
    lines = [
        "# Supported models and features",
        "",
        "<!-- Generated by scripts/docs/generate_model_reference.py; edit runner declarations or scripts/docs/model_reference_io.json. -->",
        "",
        "Choose a registered model below, then start with the [runner](runner.md).",
        "These tables describe this source checkout; installed releases can differ.",
        "**✓ means the adapter declares support; — means it does not.** Support still",
        "depends on the checkpoint, inputs, hardware, kernels, and flag combinations.",
        "Follow the linked guides for restrictions; a row does not promise every feature",
        "can be enabled together. CUDA, ROCm, and Ascend availability varies by backend.",
        "",
        "- [Parallelism](#parallelism)",
        "- [Memory and precision](#memory-and-precision)",
        "- [Communication, caching, and adapters](#communication-caching-and-adapters)",
        "- [Accepted model names and requirements](#accepted-model-names-and-requirements)",
        "",
        "## Parallelism",
        "",
        "[Ulysses and Ring](../methods/usp.md) split sequence/attention work;",
        "[CFG](../methods/cfg_parallel.md) splits guidance branches;",
        "[PipeFusion](../methods/pipefusion.md) splits transformer stages.",
        "TP is transformer tensor parallelism. [FSDP and text-encoder TP](memory.md)",
        "reuse existing ranks. VAE **D** means decode, **E** means encode support.",
        *(
            []
            if any(entry.capabilities.get("tensor_parallel_degree", False) for entry in entries)
            else [
                "No current runner model supports transformer TP (`--tensor_parallel_degree > 1`).",
                "For the legacy FLUX feed-forward TP path, see [legacy TP examples](examples.md#legacy-tensor-parallelism).",
                "Text-encoder TP is separate; see the **Text TP** column.",
            ]
        ),
        "",
        "| Model | Ulysses | Ring | CFG | PipeFusion | DP | TP | FSDP | Text TP | VAE |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    parallel_flags = (
        "ulysses_degree",
        "ring_degree",
        "use_cfg_parallel",
        "pipefusion_parallel_degree",
        "data_parallel_degree",
        "tensor_parallel_degree",
        "fully_shard_degree",
        "text_encoder_tp_degree",
    )
    for index, entry in enumerate(entries):
        values = [_flag(entry, flag) for flag in parallel_flags]
        vae = (
            "+".join(
                label
                for label, flag in (("D", "use_parallel_vae"), ("E", "use_parallel_vae_encoder"))
                if entry.capabilities.get(flag, False)
            )
            or "—"
        )
        lines.append("| " + " | ".join([_model_link(entry, index), *values, vae]) + " |")
    lines.extend(
        [
            "",
            "## Memory and precision",
            "",
            "[GEMM formats](quantization.md) apply to declared linear-layer targets,",
            "not the entire model. Text FP8 is a separate opt-in for supported encoders.",
            "[VAE tiling and slicing](../methods/parallel_vae.md) are independent memory controls.",
            "",
            "| Model | FP8 | FP4 | FP6 | A6W4 | INT8 | Text FP8 | Tiling | Slicing |",
            "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
        ]
    )
    precision_flags = (
        "use_fp8_gemms",
        "use_fp4_gemms",
        "use_fp6_gemms",
        "use_a6w4_gemms",
        "use_int8_gemms",
        "use_fp8_text_encoder",
        "enable_tiling",
        "enable_slicing",
    )
    for index, entry in enumerate(entries):
        values = [_flag(entry, flag) for flag in precision_flags]
        lines.append("| " + " | ".join([_model_link(entry, index), *values]) + " |")
    lines.extend(
        [
            "",
            "## Communication, caching, and adapters",
            "",
            "[FP8 communication and Attention A2A](communication.md) optimize Ulysses exchanges.",
            "Sparse means at least one sparse attention family is declared; consult",
            "[attention backends](attention.md) for model/kernel restrictions.",
            "[Cache methods](caching.md) come from the model presets; `pipefusion` additionally",
            "requires a compatible DBCache layout and is described in the PipeFusion guide.",
            "[LoRA](lora.md) means supported startup fusion, not runtime adapter switching.",
            "",
            "| Model | FP8 comms | Attention A2A | Sparse | Cache presets | LoRA |",
            "| --- | --- | --- | --- | --- | --- |",
        ]
    )
    for index, entry in enumerate(entries):
        sparse = any(
            entry.capabilities.get(flag, False)
            for flag in (
                "supports_sparse_attention_backends",
                "supports_sparge_attention_backends",
                "supports_sol_attention_backends",
                "supports_bsa_attention_backends",
            )
        )
        methods = ", ".join(_code(method) for method in entry.cache_methods) or "—"
        values = [
            _model_link(entry, index),
            _flag(entry, "use_fp8_comms"),
            _flag(entry, "supports_attention_a2a"),
            "✓" if sparse else "—",
            methods,
            _flag(entry, "supports_lora"),
        ]
        lines.append("| " + " | ".join(values) + " |")
    lines.extend(
        [
            "",
            "## Accepted model names and requirements",
            "",
            "Aliases in the same row use the same adapter. Checkpoint-specific task,",
            "precision, and resolution choices can still differ; the source link shows",
            "those rules. `source` means Diffusers must be installed from source.",
            "The version column records each adapter's declared minimum; an undeclared",
            "floor means the minimum is unknown. It is not a complete",
            "environment lock. See [installation and containers](installation.md).",
            "Input lists prompt text and conditioning media accepted by each adapter.",
            "Optional and task-specific inputs are labeled; check the source for image counts and other restrictions.",
            "",
            "| Model / source | Accepted `--model` names | Input | Output | Diffusers minimum |",
            "| --- | --- | --- | --- | --- |",
        ]
    )
    for index, entry in enumerate(entries):
        names = ", ".join(_code(alias) for alias in entry.aliases)
        source = f'<a id="{_anchor(entry)}"></a>[{_prose(entry.name)}]({SOURCE_ROOT}{entry.source})'
        version = _code(str(entry.diffusers)) if entry.diffusers is not None else "Not declared"
        lines.append(f"| {source} | {names} | {_prose(entry.inputs)} | {_prose(entry.output)} | {version} |")
    lines.extend(
        [
            "",
            "Some models outside this registry have [legacy example scripts](examples.md#dedicated-pipeline-examples).",
            "These scripts use the legacy parser; their support is not included in these runner tables.",
            "",
        ]
    )
    return "\n".join(lines)


def update_models(entries: Sequence[ModelEntry], output: Path, *, check: bool = False) -> int:
    """Write a snapshot or report drift without changing files in check mode."""
    generated = render_models(entries)
    if check:
        if output.exists() and output.read_text(encoding="utf-8") == generated:
            print(f"Model reference is current: {output}")
            return 0
        print("Model reference differs; run python -m scripts.docs.generate_model_reference")
        return 1
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(generated, encoding="utf-8")
    print(f"Wrote {output}")
    return 0


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Report drift without writing files.")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args(argv)
    # Import registers adapters without instantiating pipelines.
    import xfuser.model_executor.models.runner_models  # noqa: F401
    from xfuser.config.args import xFuserArgs
    from xfuser.model_executor.models.runner_models.base_model import MODEL_REGISTRY

    model_io = json.loads(IO_METADATA.read_text(encoding="utf-8"))
    entries = collect_models(MODEL_REGISTRY, lambda alias: xFuserArgs(model=alias), model_io=model_io)
    return update_models(entries, args.output, check=args.check)


if __name__ == "__main__":
    raise SystemExit(main())
